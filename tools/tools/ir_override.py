#!/usr/bin/env python3
"""Send a manual override / raw IR command to the climate transmitter over MQTT."""

from __future__ import annotations

import argparse
import json
import os
import sys
import threading
import time
import uuid
from typing import Any

DEFAULT_TOPIC = "transmit/command"
DEFAULT_ACK_TOPIC = "transmit/command/ack"
DEFAULT_DURATION = 60
MAX_DURATION = 86400


def env_int(name: str, default: int) -> int:
    try:
        return int(os.getenv(name, str(default)))
    except ValueError:
        return default


def normalize_hex(value: str) -> str:
    text = value.strip()
    if text.lower().startswith("0x"):
        text = text[2:]
    if not text or len(text) > 8:
        raise ValueError("ir_code must contain 1-8 hexadecimal digits")
    try:
        number = int(text, 16)
    except ValueError as exc:
        raise ValueError("ir_code must be hexadecimal") from exc
    if number < 0 or number > 0xFFFFFFFF:
        raise ValueError("ir_code must fit in 32 bits")
    return f"0x{number:08X}"


def build_payload(args: argparse.Namespace, request_id: str) -> dict[str, Any]:
    if args.release:
        return {"action": "release", "request_id": request_id}

    if args.raw is not None:
        return {
            "action": "raw",
            "ir_code": normalize_hex(args.raw),
            "duration_s": args.duration,
            "request_id": request_id,
        }

    payload: dict[str, Any] = {
        "action": "override",
        "duration_s": args.duration,
        "request_id": request_id,
    }
    if args.relay is not None:
        payload["relay_on"] = args.relay == "on"
    if args.temp is not None:
        payload["target_temp"] = args.temp
    if args.fan is not None:
        payload["fan_speed"] = args.fan
    return payload


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Publish a manual override or raw NEC IR command to the transmitter.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument("--host", default=os.getenv("MQTT_HOST", "localhost"),
                        help="MQTT broker host")
    parser.add_argument("--port", type=int, default=env_int("MQTT_PORT", 1883),
                        help="MQTT broker port")
    parser.add_argument("--username", default=os.getenv("MQTT_USER"),
                        help="MQTT username (or MQTT_USER)")
    parser.add_argument("--password", default=os.getenv("MQTT_PASS"),
                        help="MQTT password (or MQTT_PASS)")
    parser.add_argument("--topic", default=DEFAULT_TOPIC,
                        help="command topic")
    parser.add_argument("--ack-topic", default=DEFAULT_ACK_TOPIC,
                        help="ACK topic")
    parser.add_argument("--request-id", default=None,
                        help="request ID echoed in the ACK (auto-generated by default)")
    parser.add_argument("--timeout", type=float, default=5.0,
                        help="MQTT connect / ACK timeout in seconds")

    mode = parser.add_argument_group("command mode (choose one)")
    mode.add_argument("--release", action="store_true",
                      help="clear an active override immediately")
    mode.add_argument("--raw", metavar="HEX",
                      help="send a raw 32-bit NEC frame, e.g. 0xA1DF15EA")
    mode.add_argument("--relay", choices=("on", "off"),
                      help="override AC relay state")
    mode.add_argument("--temp", type=int,
                      help="override target temperature in Celsius (16-30)")
    mode.add_argument("--fan", choices=("off", "low", "medium", "high"),
                      help="override fan speed")

    parser.add_argument("--duration", type=int, default=DEFAULT_DURATION,
                        help="override duration in seconds; 0 means until release")
    parser.add_argument("--dry-run", action="store_true",
                        help="print the JSON payload without connecting")
    parser.add_argument("--no-wait", action="store_true",
                        help="publish without waiting for the transmitter ACK")
    return parser


def validate_args(parser: argparse.ArgumentParser, args: argparse.Namespace) -> None:
    structured = any(value is not None for value in (args.relay, args.temp, args.fan))
    modes = sum((args.release, args.raw is not None, structured))
    if modes == 0:
        parser.error("choose one mode: --release, --raw, or --relay/--temp/--fan")
    if modes > 1:
        parser.error("--release, --raw and structured fields are mutually exclusive")

    if args.duration < 0 or args.duration > MAX_DURATION:
        parser.error(f"--duration must be between 0 and {MAX_DURATION} seconds")

    if args.temp is not None and not 16 <= args.temp <= 30:
        parser.error("--temp must be between 16 and 30 Celsius")

    if args.timeout <= 0:
        parser.error("--timeout must be greater than zero")


def run_mqtt(args: argparse.Namespace, payload: dict[str, Any], request_id: str) -> int:
    try:
        import paho.mqtt.client as mqtt
    except ImportError:
        print(
            "Missing dependency: paho-mqtt. Install with:\n"
            "  python3 -m pip install -r tools/requirements.txt",
            file=sys.stderr,
        )
        return 2

    connected = threading.Event()
    acked = threading.Event()
    connection_error: str | None = None
    ack_data: dict[str, Any] = {}

    def on_connect(client, userdata, flags, reason_code, properties):
        nonlocal connection_error
        if reason_code.is_failure:
            connection_error = str(reason_code)
            connected.set()
            return
        client.subscribe(args.ack_topic, qos=1)
        connected.set()

    def on_message(client, userdata, message):
        if message.topic != args.ack_topic:
            return
        try:
            data = json.loads(message.payload.decode("utf-8"))
        except (UnicodeDecodeError, ValueError):
            return
        if data.get("request_id") not in (None, request_id):
            return
        ack_data.clear()
        ack_data.update(data)
        acked.set()

    client = mqtt.Client(
        mqtt.CallbackAPIVersion.VERSION2,
        client_id=f"ir-override-{uuid.uuid4().hex[:8]}",
    )
    if args.username:
        client.username_pw_set(args.username, args.password)
    client.on_connect = on_connect
    client.on_message = on_message

    try:
        client.connect(args.host, args.port, keepalive=30)
    except Exception as exc:  # paho raises several connection-related types
        print(f"MQTT connection failed: {exc}", file=sys.stderr)
        return 1

    client.loop_start()
    try:
        if not connected.wait(args.timeout):
            print("Timed out waiting for the MQTT connection.", file=sys.stderr)
            return 1
        if connection_error is not None:
            print(f"MQTT connection refused: {connection_error}", file=sys.stderr)
            return 1

        info = client.publish(args.topic, json.dumps(payload), qos=1)
        try:
            info.wait_for_publish(timeout=args.timeout)
        except Exception as exc:
            print(f"Publish failed: {exc}", file=sys.stderr)
            return 1

        print(f"Published to {args.topic}:")
        print(json.dumps(payload, indent=2))

        if args.no_wait:
            return 0

        if not acked.wait(args.timeout):
            print("Timed out waiting for the transmitter ACK.", file=sys.stderr)
            return 1

        print("Transmitter ACK:")
        print(json.dumps(ack_data, indent=2, sort_keys=True))
        return 0 if ack_data.get("ok") is not False else 1

    finally:
        client.disconnect()
        client.loop_stop()


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    validate_args(parser, args)

    request_id = args.request_id or f"cli-{int(time.time())}-{uuid.uuid4().hex[:6]}"

    try:
        payload = build_payload(args, request_id)
    except ValueError as exc:
        parser.error(str(exc))

    if args.dry_run:
        print(json.dumps(payload, indent=2))
        return 0

    return run_mqtt(args, payload, request_id)


if __name__ == "__main__":
    raise SystemExit(main())
